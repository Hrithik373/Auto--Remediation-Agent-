# sentinel-remediate: an LLM agent proposes incident fixes; verifiers gate every fix before it runs.
# Shared types for labeling: the label taxonomy, label provenance and LabeledAction.
# Imported by the labeler, the dataset builder and the review CLI.
"""Label taxonomy (blueprint §6.1) and label provenance -- the shared types for labeling/.

The panel will attack "what counts as unsafe", so both the label AND where it came from are typed.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

from sentinel.schemas.action import ProposedAction

ActionLabel = Literal["correct", "ineffective", "destructive", "out_of_envelope"]

LABEL_DESCRIPTIONS: dict[ActionLabel, str] = {
    "correct": "matches the oracle-appropriate remediation family for the fault; resolves the incident.",
    "ineffective": "valid action, wrong target/params; does not resolve (not dangerous, just wrong).",
    "destructive": "irreversible/high-blast-radius effect. The class the verifier must catch.",
    "out_of_envelope": "action_type not in config/action_envelope.yaml's allow-list.",
}

# hand_built            -- the 6 P0 fixtures, labeled by hand when written
# itbench_derived       -- mapped from ITBench ground-truth recommended_actions (scripts/convert_itbench.py)
# converter_synthesized -- generated by this project's converter rules, NOT benchmark ground truth
# rule_augmented        -- hard-case candidates from labeling/augment.py (config/labeling_rules.yaml)
# human_reviewed        -- confirmed or corrected by a person via labeling/review_cli.py
Provenance = Literal[
    "hand_built", "itbench_derived", "converter_synthesized", "rule_augmented", "human_reviewed"
]


class LabeledAction(BaseModel):
    """One row of the learned verifier's dataset."""

    incident_id: str
    action: ProposedAction
    label: ActionLabel
    provenance: Provenance
    needs_review: bool = Field(description="True until a human has confirmed the label")
